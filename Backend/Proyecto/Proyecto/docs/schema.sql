--
-- Diseño: todo el dominio (catálogo de países, resumen de dependencia, socios
-- por país) se cachea como JSON bajo (tipo, clave) en vez de modelarse en
-- tablas propias, porque los datos históricos de la OEC no cambian (no hace
-- falta normalizar lo que nunca se actualiza). Claves en uso:
--   tipo="CATALOGO_PAISES", clave="global"          -> catálogo completo de países
--   tipo="DEPENDENCIA",     clave="{id OEC}:{año}"  -> resumen de un país/año (ej. "sacol:2023")
--   tipo="SOCIOS",          clave="{id OEC}:{año}"  -> comercio con cada socio real de un país/año

